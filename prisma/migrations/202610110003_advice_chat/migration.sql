CREATE TABLE "AdviceThread" (
 "id" TEXT NOT NULL PRIMARY KEY,
 "userId" TEXT NOT NULL UNIQUE REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "AdviceMessage" (
 "id" TEXT NOT NULL PRIMARY KEY,
 "threadId" TEXT NOT NULL REFERENCES "AdviceThread"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "senderId" TEXT NOT NULL,
 "body" TEXT NOT NULL,
 "fromStaff" BOOLEAN NOT NULL,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "AdviceMessage_threadId_createdAt_idx" ON "AdviceMessage"("threadId", "createdAt");
