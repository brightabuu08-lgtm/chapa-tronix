import {assertIsolatedTestServer} from './isolated-server.mjs';
import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.TEST_BASE_URL||'http://localhost:3107';
await assertIsolatedTestServer(base);
const browser=await chromium.launch({channel:'chrome',headless:true});
await mkdir('test-results',{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Nimeelewa',exact:true}).click();
await page.screenshot({path:'test-results/home-desktop.png',fullPage:true});
assert.ok(await page.locator('#main h1').count());
await page.goto(base+'/product/arduino-uno-r3',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Weka kikapuni',exact:true}).click();
await page.goto(base+'/cart',{waitUntil:'networkidle'});
assert.ok(await page.getByRole('heading',{name:'Arduino Uno R3',exact:true}).count());
await page.reload({waitUntil:'networkidle'});
assert.ok(await page.getByRole('heading',{name:'Arduino Uno R3',exact:true}).count());
await page.getByRole('button',{name:'Ongeza',exact:true}).click();
assert.ok((await page.locator('.quantity').textContent()).includes('2'));
await page.goto(base+'/shop',{waitUntil:'networkidle'});
await page.locator('.catalog-search input').fill('ESP32');
await page.waitForFunction(()=>document.querySelectorAll('.catalog-grid .product-card').length===1);
await page.locator('.catalog-grid .product-card h3').click();
await page.getByRole('button',{name:'Kuza picha',exact:true}).click();
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('dialog').count(),0);
await page.getByRole('button',{name:'Switch language'}).click();
assert.equal(await page.locator('html').getAttribute('lang'),'en');
await page.goto(base+'/checkout',{waitUntil:'networkidle'});
assert.ok(await page.getByRole('heading',{name:'Complete your order'}).count());
await page.screenshot({path:'test-results/checkout-desktop.png',fullPage:true});
const mobile=await browser.newPage({viewport:{width:360,height:800},isMobile:true,deviceScaleFactor:1});
await mobile.goto(base,{waitUntil:'networkidle'});
await mobile.getByRole('button',{name:'Nimeelewa',exact:true}).click();
await mobile.screenshot({path:'test-results/home-mobile.png',fullPage:true});
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile home has no horizontal overflow');
await mobile.getByRole('button',{name:'Menu',exact:true}).click();
assert.equal(await mobile.locator('.nav-open').count(),1);
await mobile.goto(base+'/shop',{waitUntil:'networkidle'});
await mobile.getByRole('button',{name:'Chuja',exact:true}).click();
assert.ok(await mobile.locator('.filters.show').count());
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile catalog has no horizontal overflow');
await mobile.screenshot({path:'test-results/shop-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log(JSON.stringify({browserChecks:13,viewports:[360,1440],runtimeErrors:errors,result:'passed'}));
await browser.close();
